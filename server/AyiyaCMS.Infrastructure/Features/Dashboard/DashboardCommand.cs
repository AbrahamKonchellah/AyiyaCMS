// AyiyaCMS.Infrastructure/Features/Dashboard/DashboardCommand.cs
using AyiyaCMS.Application.Features.Dashboard.DTOs;
using AyiyaCMS.Infrastructure.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Caching.Memory;

namespace AyiyaCMS.Infrastructure.Features.Dashboard;

public class DashboardCommand
{
    private readonly AppDbContext _db;
    private readonly IMemoryCache _cache;

    private static readonly HashSet<string> _excludedActions = new(StringComparer.OrdinalIgnoreCase)
    {
        "Login", "Logout", "MfaEnabled", "MfaDisabled",
        "PasswordReset", "PasswordChanged", "TokenRefreshed",
    };

    public DashboardCommand(AppDbContext db, IMemoryCache cache)
    {
        _db    = db;
        _cache = cache;
    }

    // ── Stats ─────────────────────────────────────────
    public async Task<DashboardStatsDto> GetStatsAsync(Guid userId, string role)
    {
        // Cache key is per-user so Associates/Paralegals get their own scoped stats
        var cacheKey = $"dashboard:stats:{userId}";

        if (_cache.TryGetValue(cacheKey, out DashboardStatsDto? cached) && cached is not null)
            return cached;

        var now            = DateTime.UtcNow;
        var sevenDaysAhead = now.AddDays(7);
        var monthStart     = new DateTime(now.Year, now.Month, 1, 0, 0, 0, DateTimeKind.Utc);

        var mattersQuery = _db.Matters.Where(m => m.Status == "Active");

        if (role == "Associate")
            mattersQuery = mattersQuery.Where(m =>
                m.AssignedLawyerId == userId ||
                m.Staff!.Any(ms => ms.UserId == userId));

        if (role == "Paralegal")
            mattersQuery = mattersQuery.Where(m =>
                m.Staff!.Any(ms => ms.UserId == userId));

        var activeMatters = await mattersQuery.CountAsync();

        var upcomingHearings = await mattersQuery
            .Where(m => m.HearingDate >= now && m.HearingDate <= sevenDaysAhead)
            .CountAsync();

        var outstandingInvoices = await _db.Invoices
            .Where(i => i.Status == "Sent" || i.Status == "Overdue")
            .SumAsync(i => (decimal?)i.Amount) ?? 0m;

        var unbilledHours = await _db.TimeEntries
            .Where(t => !t.IsBilled && t.EntryDate >= monthStart)
            .SumAsync(t => (decimal?)t.Hours) ?? 0m;

        var result = new DashboardStatsDto
        {
            ActiveMatters          = activeMatters,
            UpcomingHearings       = upcomingHearings,
            OutstandingInvoiceKes  = outstandingInvoices,
            UnbilledHoursThisMonth = unbilledHours,
        };

        _cache.Set(cacheKey, result, TimeSpan.FromSeconds(60));
        return result;
    }

    // ── Activity feed ─────────────────────────────────
    public async Task<List<ActivityItemDto>> GetActivityAsync(Guid userId, string role)
    {
        // Activity feed is firm-wide for all roles — cache is shared but short-lived
        const string cacheKey = "dashboard:activity";

        if (_cache.TryGetValue(cacheKey, out List<ActivityItemDto>? cached) && cached is not null)
            return cached;

        var logs = await _db.AuditLogs
            .Where(a => !_excludedActions.Contains(a.Action))
            .OrderByDescending(a => a.PerformedAt)
            .Take(20)
            .ToListAsync();

        var result = logs.Select(log =>
        {
            var type = log.EntityName switch
            {
                "Document"  => "doc",
                "Invoice"   => "bill",
                "TimeEntry" => "note",
                "Matter"    => log.Action == "StatusChanged" ? "alert" : "user",
                _           => "user",
            };

            var text = (log.EntityName, log.Action) switch
            {
                ("Document",  "Uploaded")       => $"<strong>{log.PerformedBy}</strong> uploaded a document",
                ("Document",  "Deleted")        => $"<strong>{log.PerformedBy}</strong> deleted a document",
                ("Invoice",   "Created")        => $"Invoice generated by <strong>{log.PerformedBy}</strong>",
                ("Invoice",   "Sent")           => $"Invoice sent by <strong>{log.PerformedBy}</strong>",
                ("Invoice",   "Paid")           => $"Invoice marked as paid by <strong>{log.PerformedBy}</strong>",
                ("Matter",    "Created")        => $"Matter opened by <strong>{log.PerformedBy}</strong>",
                ("Matter",    "Updated")        => $"Matter updated by <strong>{log.PerformedBy}</strong>",
                ("Matter",    "StatusChanged")  => $"Matter status changed by <strong>{log.PerformedBy}</strong>",
                ("Matter",    "LawyerAssigned") => $"Lawyer assigned to matter by <strong>{log.PerformedBy}</strong>",
                ("Matter",    "StaffAdded")     => $"Staff member added to matter by <strong>{log.PerformedBy}</strong>",
                ("Matter",    "StaffRemoved")   => $"Staff member removed from matter by <strong>{log.PerformedBy}</strong>",
                ("Matter",    "Deleted")        => $"Matter deleted by <strong>{log.PerformedBy}</strong>",
                ("TimeEntry", "Created")        => $"<strong>{log.PerformedBy}</strong> logged time",
                ("Client",    "Created")        => $"New client added by <strong>{log.PerformedBy}</strong>",
                ("Client",    "Updated")        => $"Client updated by <strong>{log.PerformedBy}</strong>",
                ("User",      "Created")        => $"New user invited by <strong>{log.PerformedBy}</strong>",
                ("User",      "Deactivated")    => $"User deactivated by <strong>{log.PerformedBy}</strong>",
                ("User",      "RoleChanged")    => $"User role changed by <strong>{log.PerformedBy}</strong>",
                _ => $"<strong>{log.PerformedBy}</strong> performed {log.Action} on {log.EntityName}",
            };

            return new ActivityItemDto
            {
                Id     = log.Id.ToString(),
                Type   = type,
                Text   = text,
                Matter = null,
                Time   = log.PerformedAt,
            };
        }).ToList();

        _cache.Set(cacheKey, result, TimeSpan.FromSeconds(30));
        return result;
    }

    // ── Deadlines ─────────────────────────────────────
    public async Task<List<DeadlineItemDto>> GetDeadlinesAsync(Guid userId, string role)
    {
        var cacheKey = $"dashboard:deadlines:{userId}";

        if (_cache.TryGetValue(cacheKey, out List<DeadlineItemDto>? cached) && cached is not null)
            return cached;

        var now   = DateTime.UtcNow.Date;
        var limit = now.AddDays(7);

        var mattersQuery = _db.Matters
            .Include(m => m.Client)
            .Where(m => m.Status == "Active");

        if (role == "Associate")
            mattersQuery = mattersQuery.Where(m =>
                m.AssignedLawyerId == userId ||
                m.Staff!.Any(ms => ms.UserId == userId));

        if (role == "Paralegal")
            mattersQuery = mattersQuery.Where(m =>
                m.Staff!.Any(ms => ms.UserId == userId));

        var matters = await mattersQuery
            .Where(m =>
                (m.HearingDate.HasValue    && m.HearingDate.Value.Date    >= now && m.HearingDate.Value.Date    <= limit) ||
                (m.FilingDeadline.HasValue && m.FilingDeadline.Value.Date >= now && m.FilingDeadline.Value.Date <= limit))
            .ToListAsync();

        var deadlines = new List<DeadlineItemDto>();

        foreach (var m in matters)
        {
            var matterLabel = $"{m.Client?.Name} — {m.Title}".Trim();

            if (m.HearingDate.HasValue && m.HearingDate.Value.Date >= now && m.HearingDate.Value.Date <= limit)
                deadlines.Add(new DeadlineItemDto
                {
                    Id     = $"{m.Id}-hearing",
                    Title  = "Hearing",
                    Matter = matterLabel,
                    Date   = m.HearingDate.Value,
                });

            if (m.FilingDeadline.HasValue && m.FilingDeadline.Value.Date >= now && m.FilingDeadline.Value.Date <= limit)
                deadlines.Add(new DeadlineItemDto
                {
                    Id     = $"{m.Id}-filing",
                    Title  = "Filing Deadline",
                    Matter = matterLabel,
                    Date   = m.FilingDeadline.Value,
                });
        }

        var result = deadlines.OrderBy(d => d.Date).ToList();
        _cache.Set(cacheKey, result, TimeSpan.FromSeconds(60));
        return result;
    }
}